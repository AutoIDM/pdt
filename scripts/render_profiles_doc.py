"""Write docs/profiles.md from the data in pdt.profiles.

    render_profiles_doc.py            # write the file
    render_profiles_doc.py --check    # exit 1 when the file is stale

Every word in the file comes from the profile modules (DESCRIPTION, KEYS,
COMMANDS, ANSWERS) and from pdt.profiles.CONCERNS, so the docs cannot say
something the code does not.
"""

from __future__ import annotations

import argparse
import difflib
import sys
from pathlib import Path

REPO = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(REPO / "src"))

from pdt import profiles  # noqa: E402

TARGET = REPO / "docs" / "profiles.md"
PROVIDER_COLUMNS = (("aws", "AWS"), ("azure", "Azure"), ("google-cloud", "Google Cloud"),
                    ("windows", "Windows"))


def cell(text: str) -> str:
    return text.replace("|", "\\|").replace("\n", " ")


def render() -> str:
    lines = [
        "# App profiles",
        "",
        "An app profile is the shape of what pdt deploys for an app. The `app_profile` key in an app's own `pdt.yml`, or in its `apps:` entry in the project's `pdt.yml`, picks one; an app that sets none is a `" + profiles.DEFAULT + "`. The profile decides which config keys the app may set, what each `pdt` command means for it, and which resources each provider creates for it.",
        "",
        "Every profile answers the same concerns on every provider:",
        "",
    ]
    for name, description in profiles.CONCERNS:
        lines.append(f"- **{name}**: {description}")
    for name in profiles.NAMES:
        module = profiles.module(name)
        lines += ["", f"## `{name}`", "", module.DESCRIPTION[0].upper() + module.DESCRIPTION[1:] + "."]
        keys = ", ".join(f"`{key}`" for key in sorted(module.KEYS))
        lines += ["", f"Config keys only this profile uses: {keys}.", ""]
        lines += ["| Command | What it means |", "| --- | --- |"]
        for command, meaning in module.COMMANDS.items():
            lines.append(f"| `pdt {command}` | {cell(meaning)} |")
        header = " | ".join(label for _id, label in PROVIDER_COLUMNS)
        lines += ["", f"| Concern | {header} |", "| --- |" + " --- |" * len(PROVIDER_COLUMNS)]
        for concern in profiles.CONCERN_NAMES:
            answers = " | ".join(cell(module.ANSWERS[provider][concern])
                                 for provider, _label in PROVIDER_COLUMNS)
            lines.append(f"| {concern} | {answers} |")
    lines += ["", "This file is generated by `scripts/render_profiles_doc.py` from `src/pdt/profiles/`. Edit the profile modules, then run the script.", ""]
    return "\n".join(lines)


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true",
                        help="exit 1 when docs/profiles.md differs from the rendered text")
    args = parser.parse_args()
    text = render()
    if not args.check:
        TARGET.write_text(text, encoding="utf-8")
        return 0
    current = TARGET.read_text(encoding="utf-8") if TARGET.is_file() else ""
    if current == text:
        return 0
    diff = difflib.unified_diff(current.splitlines(), text.splitlines(),
                                str(TARGET.relative_to(REPO)), "rendered", lineterm="")
    sys.stdout.write("\n".join(diff) + "\n")
    sys.stdout.write(f"{TARGET.relative_to(REPO)} is stale; run scripts/render_profiles_doc.py\n")
    return 1


if __name__ == "__main__":
    sys.exit(main())
